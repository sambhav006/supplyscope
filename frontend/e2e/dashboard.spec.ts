import {test,expect} from '@playwright/test';
test('real API dashboard, filters, navigation, scenario and exports',async({page,request})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.locator('.kpis')).toBeVisible();
 const s=await (await request.get('/api/summary')).json();
 await expect(page.locator('.kpi-0 strong')).toHaveText(s.orders.toLocaleString('en-US'));
 await page.screenshot({path:'../docs/screenshots/overview.png',fullPage:true});
 await page.pdf({path:'../reports/executive_summary.pdf',format:'A4',printBackground:true});
 await page.getByLabel('Destination',{exact:true}).selectOption('RJ');
 await expect(page).toHaveURL(/region=RJ/);
 const r=await (await request.get('/api/summary?region=RJ')).json();
 await expect(page.locator('.kpi-0 strong')).toHaveText(r.orders.toLocaleString('en-US'));
 await page.reload();await expect(page.getByLabel('Destination',{exact:true})).toHaveValue('RJ');
 await page.getByRole('button',{name:'Reset filters'}).click();
 await page.getByRole('button',{name:'Seller performance',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Seller reliability scorecards'})).toBeVisible();
 await expect(page.locator('tbody tr').first()).toBeVisible();
 await page.getByLabel('Search segments').fill('NO_SUCH_SELLER');
 await expect(page.getByText('No segments match this investigation.')).toBeVisible();
 await page.getByLabel('Search segments').fill('');
 await page.getByRole('button',{name:'On time',exact:true}).click();
 await page.screenshot({path:'../docs/screenshots/sellers.png',fullPage:false});
 await page.getByRole('button',{name:'Regions & lanes',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Where service varies'})).toBeVisible();
 await page.locator('.segment-link').filter({hasText:'RJ'}).first().click();
 await expect(page.getByRole('heading',{name:'Delay contribution explorer'})).toBeVisible();
 await expect(page.getByLabel('Destination',{exact:true})).toHaveValue('RJ');
 await page.getByRole('button',{name:'Reset filters'}).click();
 await page.getByRole('button',{name:'Improvement scenarios',exact:true}).click();
 await expect(page.getByLabel('Scenario segment')).toBeVisible();
 await page.getByLabel('Scenario segment').selectOption('RJ');
 await expect(page.locator('.scenario-result')).toBeVisible();
 await page.getByLabel('Improvement percent').fill('100');
 await expect(page.getByText('Late orders becoming on time: 100%')).toBeVisible();
 await page.screenshot({path:'../docs/screenshots/scenario.png',fullPage:true});
 await page.getByRole('button',{name:'Delivery trends',exact:true}).click();
 await page.getByLabel('Trend interval').selectOption('week');
 await expect(page.getByRole('heading',{name:'Delivery reliability by week'})).toBeVisible();
 await page.getByRole('button',{name:'Data trust & methodology',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Trust starts with the denominator'})).toBeVisible();
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('link',{name:'Export CSV'}).click();
 const download=await downloadPromise;expect(download.suggestedFilename()).toBe('supplyscope-investigation.csv');
 const metadata=await (await request.get('/api/export?format=metadata&region=RJ')).json();expect(metadata.filters.region).toBe('RJ');
 expect(errors).toEqual([]);
});
